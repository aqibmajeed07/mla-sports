export const getBatByIdOrSlug = (idOrSlug) => {
  if (!idOrSlug) return null;
  return CRICKET_BATS.find(
    (bat) =>
      bat.id === idOrSlug ||
      bat.slug === idOrSlug ||
      (bat.aliases && bat.aliases.includes(idOrSlug)) ||
      bat.id.toLowerCase().includes(idOrSlug.toLowerCase()) ||
      bat.slug.toLowerCase().includes(idOrSlug.toLowerCase())
  );
};
